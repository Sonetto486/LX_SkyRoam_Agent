def import_popularity_data():
    """导入热门景点热度数据"""
    try:
        # 连接数据库
        conn = psycopg2.connect(
            dbname=settings.RAG_DB_NAME,
            user=settings.RAG_DB_USER,
            password=settings.RAG_DB_DB_PASSWORD if hasattr(settings, 'RAG_DB_DB_PASSWORD') else settings.RAG_DB_PASSWORD,
            host=settings.RAG_DB_HOST,
            port=settings.RAG_DB_PORT
        )
        cursor = conn.cursor()

        logger.info("开始导入热门景点热度数据...")

        total_imported = 0
        total_updated = 0

        for city, attractions in HOT_ATTRACTIONS_DATA.items():
            logger.info(f"处理城市: {city}")

            for name, rank, score, tags in attractions:
                try:
                    # 尝试查找对应的POI景点ID
                    cursor.execute(
                        "SELECT id FROM poi_attractions WHERE city_zh = %s AND name_zh = %s LIMIT 1",
                        (city, name)
                    )
                    result = cursor.fetchone()
                    attraction_id = result[0] if result else None

                    # 插入或更新热度数据
                    cursor.execute("""
                        INSERT INTO attraction_popularity (attraction_id, name_zh, city_zh, popularity_rank, popularity_score, tags, source)
                        VALUES (%s, %s, %s, %s, %s, %s, 'manual')
                        ON CONFLICT (city_zh, name_zh) DO UPDATE SET
                            popularity_rank = EXCLUDED.popularity_rank,
                            popularity_score = EXCLUDED.popularity_score,
                            tags = EXCLUDED.tags,
                            updated_at = CURRENT_TIMESTAMP
                    """, (attraction_id, name, city, rank, score, tags))

                    if cursor.rowcount > 0:
                        if 'INSERT' in cursor.statusmessage:
                            total_imported += 1
                        else:
                            total_updated += 1

                except Exception as e:
                    logger.warning(f"导入景点 {name} ({city}) 失败: {e}")
                    continue

        conn.commit()
        cursor.close()
        conn.close()

        logger.info(f"热度数据导入完成: 新增 {total_imported} 条, 更新 {total_updated} 条")
        return True

    except Exception as e:
        logger.error(f"导入热度数据失败: {e}")
        return False


if __name__ == "__main__":
    import_popularity_data()
